#!/usr/bin/env python3
"""Write HbRuntime/HbRuntime.UniSort.cs from Harbour's src/codepage/utf8sort.c:
the sort weight of every 16-bit character, by which the UTF8EX code page
orders strings (cp_utf8.c's UTF8_cmp) and HbRuntime's StrCmp() does too.

Run it when Harbour's table changes:  python3 genunisort.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SOURCE = os.path.join(ROOT, "src", "codepage", "utf8sort.c")
TARGET = os.path.join(HERE, "..", "HbRuntime", "HbRuntime.UniSort.cs")


def main():
    text = open(SOURCE, encoding="latin-1").read()
    start = text.index("s_uniSort[ 65536 ]")
    body = text[text.index("{", start) + 1:text.index("};", start)]
    weights = [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", body)]
    if len(weights) != 65536:
        raise SystemExit("utf8sort.c: %d weights, 65536 expected" % len(weights))
    lines = [
        "// Generated by tools/genunisort.py from Harbour's src/codepage/utf8sort.c",
        "// (Simple unicode sort table, Copyright 2012 Przemyslaw Czerpak, under",
        "// Harbour's licence): the sort weight of every 16-bit character. Do not edit.",
        "",
        "public static partial class HbRuntime",
        "{",
        "    static readonly ushort[] s_aUniSort =",
        "    {",
    ]
    for i in range(0, 65536, 16):
        lines.append("        " + ", ".join(str(w) for w in weights[i:i + 16]) + ",")
    lines += ["    };", "}", ""]
    with open(TARGET, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("%s: 65536 weights" % os.path.relpath(TARGET, ROOT))


main()
